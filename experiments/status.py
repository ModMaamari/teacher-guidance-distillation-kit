#!/usr/bin/env python
"""Render experiments/REGISTRY.md from experiments/registry.yaml and check it against results/.

    python experiments/status.py          # write REGISTRY.md, print a one-line summary
    python experiments/status.py --check  # also exit 1 if a done/partial entry lacks its results README,
                                          # or a done entry has no data file next to that README

The registry is the only place status is edited (docs/RESEARCH_WORKFLOW.md).
"""
from __future__ import annotations

import argparse
import collections
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
KIT = HERE.parent
STATUSES = ("planned", "running", "partial", "done", "superseded", "dropped")
MARK = {"done": "✅ done", "partial": "🟡 partial", "running": "🔵 running", "planned": "⚪ planned",
        "superseded": "↩ superseded", "dropped": "✖ dropped"}


def problems(entries):
    out = []
    ids = [e["id"] for e in entries]
    for dup in {i for i in ids if ids.count(i) > 1}:
        out.append(f"duplicate id {dup}")
    for e in entries:
        if e.get("status") not in STATUSES:
            out.append(f"{e['id']}: unknown status {e.get('status')!r}")
        if not (KIT / e["folder"]).is_dir():
            out.append(f"{e['id']}: missing folder {e['folder']}")
        res = KIT / e["results"]
        if e.get("status") in ("done", "partial") and not (res / "README.md").is_file():
            out.append(f"{e['id']}: status {e['status']} but no {e['results']}/README.md")
        if e.get("status") == "done" and not [p for p in res.glob("*") if p.name != "README.md"]:
            out.append(f"{e['id']}: status done but {e['results']} holds no data next to its README")
    return out


def render(entries):
    rows = ["# Experiment registry", "",
            "Generated by `python experiments/status.py` from `experiments/registry.yaml` — edit the YAML, "
            "not this file. Workflow: `docs/RESEARCH_WORKFLOW.md`.", "",
            "| ID | Experiment | Question | Tier | Status | Judge | Results | Paper | Next |",
            "|---|---|---|---|---|---|---|---|---|"]
    for e in entries:
        res = KIT / e["results"]
        link = f"[`{e['results']}`](../{e['results']})" if res.exists() else "—"
        rows.append(f"| {e['id']} | [{e['name']}](../{e['folder']}) | {e['question']} | {e.get('tier', '')} | "
                    f"{MARK.get(e['status'], e['status'])} | {e.get('judge', '—')} | {link} | `{e.get('paper', '')}` | "
                    f"{e.get('next', '')} |")
    counts = collections.Counter(e["status"] for e in entries)
    rows += ["", "**Totals:** " + ", ".join(f"{counts[s]} {s}" for s in STATUSES if counts[s]), ""]
    return "\n".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    entries = yaml.safe_load((HERE / "registry.yaml").read_text(encoding="utf-8"))["experiments"]
    (HERE / "REGISTRY.md").write_text(render(entries), encoding="utf-8")
    counts = collections.Counter(e["status"] for e in entries)
    print(f"wrote experiments/REGISTRY.md: {len(entries)} experiments ("
          + ", ".join(f"{counts[s]} {s}" for s in STATUSES if counts[s]) + ")")
    issues = problems(entries)
    for p in issues:
        print(f"  ! {p}")
    return 1 if (args.check and issues) else 0


if __name__ == "__main__":
    sys.exit(main())
